"""CMake module descriptor validation, resolution and native registration generation."""



import glob

import json

import os

import re



DX12_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DESC_DIR_REL = "src/Modules"

KINDS = ("cpp", "script", "content")

KEYS = {"name", "kind", "summary", "dependsOn", "enabledByDefault", "engineClass", "editorClass",
        "lib", "sources", "components", "assetExts", "luaTables", "importedDlls", "runtimeDlls",
        "dllDirs", "contentRoots", "shaderDirs", "scripts", "scriptNames", "defines", "includeDirs", "noPch",
        "dllsOptional"}

NAME_RE = re.compile(r"^[A-Z][A-Za-z0-9]*$")

class ModuleError(Exception):
    pass

def load_descriptors(root=None):
    """{name: descriptor} - every src/Modules/*.module.json, validated on its own."""
    root = root or DX12_DIR
    out = {}
    for full in sorted(glob.glob(os.path.join(root, DESC_DIR_REL, "*.module.json"))):
        rel = os.path.relpath(full, root).replace("\\", "/")
        try:
            with open(full, encoding="utf-8") as f:
                d = json.load(f)
        except (OSError, ValueError) as e:
            raise ModuleError("%s: %s" % (rel, e))
        if not isinstance(d, dict):
            raise ModuleError("%s: not a JSON object" % rel)
        unknown = sorted(set(d) - KEYS - {"_comment"})
        if unknown:
            raise ModuleError("%s: unknown key(s) %s" % (rel, ", ".join(unknown)))
        name = d.get("name")
        if not isinstance(name, str) or not NAME_RE.match(name):
            raise ModuleError("%s: name must be PascalCase" % rel)
        if os.path.basename(full) != name + ".module.json":
            raise ModuleError("%s: the file must be named %s.module.json" % (rel, name))
        if d.get("kind") not in KINDS:
            raise ModuleError("%s: kind must be one of %s" % (rel, ", ".join(KINDS)))
        if d["kind"] == "cpp" and not d.get("engineClass"):
            raise ModuleError("%s: a cpp module names its engineClass" % rel)
        if d["kind"] != "cpp" and (d.get("engineClass") or d.get("editorClass") or d.get("lib")):
            raise ModuleError("%s: only a cpp module has classes or a lib" % rel)
        d.setdefault("summary", "")
        d.setdefault("dependsOn", [])
        d.setdefault("enabledByDefault", True)
        for k in ("sources", "components", "assetExts", "luaTables", "importedDlls", "runtimeDlls",
                  "dllDirs", "contentRoots", "shaderDirs", "scripts", "scriptNames", "defines", "includeDirs", "noPch",
                  "dependsOn"):
            d.setdefault(k, [])
            if not isinstance(d[k], list) or not all(isinstance(x, str) for x in d[k]):
                raise ModuleError("%s: %s must be a list of strings" % (rel, k))
        if d.get("lib") and d["lib"] != name:
            raise ModuleError("%s: lib must be the module's name (%s)" % (rel, name))
        d["_file"] = rel
        out[name] = d
    for name, d in out.items():
        for dep in d["dependsOn"]:
            if dep not in out:
                raise ModuleError("%s: depends on unknown module %s" % (d["_file"], dep))
            if dep == name:
                raise ModuleError("%s: depends on itself" % d["_file"])
    order(out, list(out))   # raises on a cycle
    return out

def order(descs, names):
    """@p names and every dependency, dependencies first; ties by name. Raises on a cycle."""
    done, visiting, out = set(), [], []

    def visit(n):
        if n in done:
            return
        if n in visiting:
            raise ModuleError("dependency cycle: %s" % " -> ".join(visiting[visiting.index(n):] + [n]))
        visiting.append(n)
        for dep in sorted(descs[n]["dependsOn"]):
            visit(dep)
        visiting.pop()
        done.add(n)
        out.append(n)

    for n in sorted(names):
        visit(n)
    return out

def resolve(descs, choices):
    """The enabled modules for a project's @p choices ({name: bool} or None), dependencies first."""
    choices = choices or {}
    for n in choices:
        if n not in descs:
            raise ModuleError("game.json names unknown module %s" % n)
    wanted = [n for n, d in descs.items() if choices.get(n, d["enabledByDefault"])]
    enabled = order(descs, wanted)
    for n in enabled:
        if choices.get(n) is False:
            needers = sorted(m for m in enabled if n in descs[m]["dependsOn"])
            raise ModuleError("%s is turned off in game.json, but %s depend%s on it"
                              % (n, ", ".join(needers), "s" if len(needers) == 1 else ""))
    return enabled

def render(descs, linked, label):
    """The registration list: every module declared, the C++ ones in @p linked linked."""
    cpp = [n for n in linked if descs[n]["kind"] == "cpp"]
    lines = [
        "// GENERATED by tools/gen_modules.py - do not edit.",
        "//",
        "// %s" % label,
        "// Compiled per exe (Game.vcxproj, Editor.vcxproj), never into EngineCore: calling a",
        "// module's factory is what links its objects into the exe, and a module this list does",
        "// not call is not in the exe at all. verify's offline gate modules fails while the",
        "// checked-in list is stale.",
        "",
        '#include "Module/ModuleRegistry.h"',
        "#ifdef WITH_EDITOR",
        '#include "Editor/EditorModule.h"',
        "#endif",
        "",
    ]
    for n in cpp:
        lines.append("std::unique_ptr<Module::IEngineModule> CreateEngineModule_%s();   // %s"
                     % (descs[n]["engineClass"], n))
    eds = [n for n in cpp if descs[n].get("editorClass")]
    if eds:
        lines.append("#ifdef WITH_EDITOR")
        for n in eds:
            lines.append("std::unique_ptr<Editor::IEditorModule> CreateEditorModule_%s();   // %s"
                         % (descs[n]["editorClass"], n))
        lines.append("#endif")
    if cpp:
        lines.append("")
    lines += ["void Module::RegisterLinkedModules(Module::Registry& registry)", "{"]
    for n in order(descs, list(descs)):
        d = descs[n]
        def braces(items):
            return "{ %s }" % ", ".join('"%s"' % x for x in items) if items else "{}"
        lines.append('    registry.Declare({ "%s", Module::Kind::%s, %s, %s, %s, %s });'
                     % (n, d["kind"].capitalize(), braces(sorted(d["dependsOn"])),
                        "true" if d["enabledByDefault"] else "false", braces(d["components"]),
                        braces(d["scripts"])))
    for n in cpp:
        lines.append('    registry.Link("%s", &CreateEngineModule_%s);' % (n, descs[n]["engineClass"]))
    lines += ["}", ""]
    lines += ["#ifdef WITH_EDITOR", "void Editor::RegisterLinkedEditorModules(Editor::ModuleRegistry& registry)", "{"]
    if not eds:
        lines.append("    (void)registry;")
    for n in eds:
        lines.append('    registry.Link("%s", &CreateEditorModule_%s);' % (n, descs[n]["editorClass"]))
    lines += ["}", "#endif", ""]
    return "\n".join(lines)

def manifest(descs, enabled, project, root=None):
    """modules.json: what package_game.py and module_link_gate.py need of a project's set."""
    root = root or DX12_DIR
    out = {"project": project, "enabled": enabled,
           "disabled": sorted(n for n in descs if n not in enabled), "modules": {}}
    for n, d in descs.items():
        out["modules"][n] = {k: d[k] for k in ("kind", "dependsOn", "lib", "engineClass", "sources",
                                                "components", "assetExts", "luaTables", "importedDlls",
                                                "runtimeDlls", "dllDirs", "contentRoots", "shaderDirs", "scripts",
                                                "scriptNames")
                             if k in d}
    return out

def glob_regex(pattern):
    """A DX12-relative glob (* within a folder, ** across folders) as a compiled regex."""
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$", re.IGNORECASE)

def owner_table(descs):
    return [(n, glob_regex(p)) for n, d in sorted(descs.items()) for p in d["sources"]]

def module_of(rel, table):
    """The module owning DX12-relative @p rel, or None (the core)."""
    rel = rel.replace("\\", "/")
    for n, rx in table:
        if rx.match(rel):
            return n
    return None


def write_set(out_dir, descs, enabled, name, root):
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, 'Modules.generated.cpp'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(render(descs, enabled, 'CMake module registration.'))
    with open(os.path.join(out_dir, 'modules.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(manifest(descs, enabled, name, root), f, indent=2)
        f.write('\n')
